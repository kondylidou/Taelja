-- Terms and literals -----------------------------------------------------

symName :: Ctx -> Sym -> String
symName ctx s = Map.findWithDefault "taelja_undeclared_symbol" s (ctxNames ctx)

term :: Ctx -> Env -> Term -> String
term _   env (Var v)    = Map.findWithDefault "taelja_unbound_variable" v env
term ctx _   (Const c)  = symName ctx (Fun, c, 0)
term ctx env (App f ts) = unwords (symName ctx (Fun, f, length ts) : map (arg ctx env) ts)

-- A term as an argument, in parentheses when it is an application.
arg :: Ctx -> Env -> Term -> String
arg ctx env t@(App _ (_ : _)) = "(" ++ term ctx env t ++ ")"
arg ctx env t                 = term ctx env t

literal :: Ctx -> Env -> Literal -> String
literal ctx env l = case l of
  Eq a b    -> term ctx env a ++ " = " ++ term ctx env b
  NEq a b   -> term ctx env a ++ " ≠ " ++ term ctx env b
  Rel p ts  -> atom p ts
  NRel p ts -> "¬ (" ++ atom p ts ++ ")"
  where atom p ts | p == "$false" = "False"
                  | p == "$true"  = "True"
                  | otherwise     = unwords (symName ctx (Pred, p, length ts) : map (arg ctx env) ts)

-- Lean names for variables, in order, none of them a name already in use.
bindVars :: Set.Set String -> Env -> [String] -> Env
bindVars used env0 vs = foldl bind env0 (nub vs)
  where
    bind env v | v `Map.member` env = env
               | otherwise = Map.insert v (head (filter (free env) candidates)) env
    free env x = x `Set.notMember` used && x `notElem` Map.elems env && not (reservedName x)
    candidates = ["x", "y", "z", "u", "v", "w"] ++ [ "x" ++ show n | n <- [(1 :: Int) ..] ]

quantified :: [String] -> String -> String
quantified [] body = body
quantified vs body = "∀ (" ++ unwords vs ++ " : α), " ++ body

-- A lemma or goal, universally closed over its variables in order of
-- occurrence.
statement :: Ctx -> Literal -> String
statement ctx lit = quantified (map (env Map.!) vs) (literal ctx env lit)
  where vs  = nub (litVars lit)
        env = bindVars (ctxUsed ctx) Map.empty vs

-- A clause b1 /\ ... /\ bn => h as b1 → ... → bn → h under its variables.
refType :: Ctx -> Ref -> String
refType ctx r = quantified (map (env Map.!) (refBinders r)) $
  intercalate " → " (map hyp (refBody r) ++ [maybe "False" (literal ctx env) (refHead r)])
  where
    env = bindVars (ctxUsed ctx) Map.empty (refBinders r)
    hyp b = case b of
      NEq _ _  -> "(" ++ literal ctx env b ++ ")"
      NRel _ _ -> "(" ++ literal ctx env b ++ ")"
      _        -> literal ctx env b

-- Matching ---------------------------------------------------------------

-- One-way matching of a pattern against a term of the proof.  Only the
-- variables the predicate admits are bound, and every other variable stands
-- for itself.
matchT :: (String -> Bool) -> Term -> Term -> Sub -> Maybe Sub
matchT bindable p t s = case (p, t) of
  (Var v, _) | bindable v -> case Map.lookup v s of
    Nothing -> Just (Map.insert v t s)
    Just t' -> if t' == t then Just s else Nothing
  (Var v, Var w)   | v == w -> Just s
  (Const c, Const d) | c == d -> Just s
  (App f as, App g bs) | f == g, length as == length bs ->
    foldM (\s' (a, b) -> matchT bindable a b s') s (zip as bs)
  _ -> Nothing

-- The ways a pattern literal matches a literal, with whether the equation
-- is matched the other way round.
matchL :: (String -> Bool) -> Literal -> Literal -> Sub -> [(Sub, Bool)]
matchL bindable p l s = case (p, l) of
  (Eq a b, Eq c d)   -> sides a b c d
  (NEq a b, NEq c d) -> sides a b c d
  (Rel f as, Rel g bs)   | f == g, length as == length bs -> args as bs
  (NRel f as, NRel g bs) | f == g, length as == length bs -> args as bs
  _ -> []
  where
    m = matchT bindable
    sides a b c d = [ (s', False) | Just s' <- [m a c s >>= m b d] ]
                 ++ [ (s', True)  | Just s' <- [m a d s >>= m b c] ]
    args as bs = [ (s', False) | Just s' <- [foldM (\s' (a, b) -> m a b s') s (zip as bs)] ]

isPattern :: String -> Bool
isPattern ('?' : _) = True
isPattern _         = False

flipLit :: Literal -> Literal
flipLit (Eq a b)  = Eq b a
flipLit (NEq a b) = NEq b a
flipLit l         = l

symm :: Literal -> String -> String
symm (NEq _ _) t = "Ne.symm (" ++ t ++ ")"
symm _         t = "Eq.symm (" ++ t ++ ")"

-- The cited statement applied to the values of its variables.  A variable
-- the step leaves free holds for every value, so an element stands for it.
instantiate :: Ctx -> Env -> Ref -> Sub -> String
instantiate ctx env r s = unwords (refName r : [ maybe "taelja_elem" (arg ctx env) (Map.lookup b s) | b <- refBinders r ])

-- Rewriting --------------------------------------------------------------

holeVar :: String
holeVar = "\0hole"

-- Corresponding subterms of two terms that differ, outermost first.
diffPairs :: Term -> Term -> [(Term, Term)]
diffPairs a b
  | a == b    = []
  | otherwise = (a, b) : case (a, b) of
      (App f as, App g bs) | f == g, length as == length bs -> concat (zipWith diffPairs as bs)
      _ -> []

-- The first term with every place where it holds l and the second holds r
-- replaced by the hole, if that accounts for every difference.
abstract :: (Term, Term) -> Term -> Term -> Maybe Term
abstract (l, r) p c
  | p == l, c == r = Just (Var holeVar)
  | p == c         = Just p
  | App f as <- p, App g bs <- c, f == g, length as == length bs =
      App f <$> zipWithM (abstract (l, r)) as bs
  | otherwise      = Nothing

-- A step from the first components to the second by one instance of the
-- cited equation, read in the printed direction: the proof of that instance
-- l = r, with l in the first components and r in the second, and the
-- components with the rewritten places abstracted.
rewrite :: Ctx -> Env -> Ref -> [Dir] -> [(Term, Term)] -> Maybe (String, [Term])
rewrite ctx env r dirs comps = case refHead r of
  Just (Eq l0 r0) | null (refBody r) -> listToMaybe
    [ (if d == LR then inst else "Eq.symm (" ++ inst ++ ")", ctxs)
    | d <- dirs
    , let (from, to) = if d == LR then (l0, r0) else (r0, l0)
    , (x, y) <- concatMap (uncurry diffPairs) comps
    , Just s <- [matchT isPattern from x Map.empty >>= matchT isPattern to y]
    , Just ctxs <- [mapM (\(p, c) -> abstract (x, y) p c) comps]
    , let inst = instantiate ctx env r s ]
  _ -> Nothing

-- Proofs -----------------------------------------------------------------

unjustified :: String -> [String]
unjustified why = [ "-- not justified: " ++ why, "exact taelja_step_not_justified" ]

proofLines :: Ctx -> Literal -> ProofBlock -> [String]
proofLines ctx stmt blk0 =
  [ "intro " ++ unwords (map (env Map.!) stmtVs) | not (null stmtVs) ]
  ++ [ "have " ++ env Map.! v ++ " : α := taelja_elem" | v <- blockVs ]
  ++ case blk of
       HaveHence ls    -> haveHence ctx env stmt ls
       EqChain s steps -> chain ctx env hole stmt s steps
  where
    stmtVs  = nub (litVars stmt)
    blk     = specialize stmtVs stmt blk0
    blockVs = nub (blockShownVars blk) \\ stmtVs
    env0    = bindVars (ctxUsed ctx) Map.empty (stmtVs ++ blockVs)
    hole    = head [ h | h <- "t" : [ "t" ++ show n | n <- [(1 :: Int) ..] ]
                       , h `Set.notMember` ctxUsed ctx, h `notElem` Map.elems env0 ]
    env     = Map.insert holeVar hole env0

-- The variables of a block that its statement does not have are schematic,
-- the block holding for each of their values.  When the block ends on a
-- fact more general than the statement, they take the values that make it
-- the statement.
specialize :: [String] -> Literal -> ProofBlock -> ProofBlock
specialize stmtVs stmt blk = case blk of
  HaveHence ls | (l : _) <- reverse (map lineLit ls), Just s <- by l -> HaveHence (map (line s) ls)
  EqChain s steps | (Eq _ _) <- stmt, ((_, t) : _) <- reverse steps, Just sub <- by (Eq s t) ->
    EqChain (applySub sub s) [ (rw, applySub sub u) | (rw, u) <- steps ]
  _ -> blk
  where
    local v = v `notElem` stmtVs
    by l | l == stmt || flipLit l == stmt = Nothing
         | otherwise = listToMaybe [ s | (s, _) <- matchL local l stmt Map.empty, not (Map.null s) ]
    line s ln = case ln of
      Have l n  -> Have  (mapLiteralTerms (applySub s) l) n
      And l n   -> And   (mapLiteralTerms (applySub s) l) n
      Hence l j -> Hence (mapLiteralTerms (applySub s) l) j

-- A have/hence block.  The premises of a hence line are the line before it
-- and the and lines since.
haveHence :: Ctx -> Env -> Literal -> [ProofLine] -> [String]
haveHence ctx env stmt = go (1 :: Int) Nothing []
  where
    go _ cur _ [] = case cur of
      Just (h, l) | l == stmt         -> [ "exact " ++ h ]
                  | flipLit l == stmt -> [ "exact " ++ symm l h ]
      Just (_, l) -> unjustified ("the block ends on " ++ literal ctx env l ++ ", which is not the statement")
      Nothing     -> unjustified "the block is empty"
    go n cur extras (ln : rest) =
      let h = hypName n
          have l t = "have " ++ h ++ " : " ++ literal ctx env l ++ " := " ++ t
      in case ln of
        Have l nm -> case ref nm >>= \r -> horn r l [] of
          Just t  -> have l t : go (n + 1) (Just (h, l)) [] rest
          Nothing -> unjustified (nm ++ " does not state " ++ literal ctx env l)
        And l nm -> case ref nm >>= \r -> horn r l [] of
          Just t  -> have l t : go (n + 1) cur (extras ++ [(h, l)]) rest
          Nothing -> unjustified (nm ++ " does not state " ++ literal ctx env l)
        Hence l (ByAxiom nm) -> case ref nm >>= \r -> horn r l (maybeToList cur ++ extras) of
          Just t  -> have l t : go (n + 1) (Just (h, l)) [] rest
          Nothing -> unjustified (nm ++ " does not derive " ++ literal ctx env l ++ " from the lines before it")
        Hence l (ByRw nm md) -> case (cur, ref nm) of
          (Just (hp, lp), Just r)
            | Just comps <- components lp l
            , Just (eq, ctxs) <- rewrite ctx env r (maybe [LR, RL] (: []) md) comps
            , Just shape <- rebuild lp ctxs ->
                have l ("Eq.mp (congrArg (fun " ++ env Map.! holeVar ++ " : α => "
                        ++ literal ctx env shape ++ ") (" ++ eq ++ ")) " ++ hp)
                  : go (n + 1) (Just (h, l)) [] rest
          _ -> unjustified (nm ++ " does not rewrite the line before into " ++ literal ctx env l)
        Hence l ByContradiction -> case cur of
          Just (hp, lp) | lp == falsumLit -> have l ("False.elim " ++ hp) : go (n + 1) (Just (h, l)) [] rest
          _ -> unjustified "no contradiction was derived before this line"
    hypName n = localName ctx env ("h" ++ show n)
    ref nm = Map.lookup nm (ctxRefs ctx)
    horn = applyClause ctx env
    components lp l = case (lp, l) of
      (Eq a b, Eq c d)   -> Just [(a, c), (b, d)]
      (NEq a b, NEq c d) -> Just [(a, c), (b, d)]
      (Rel p as, Rel q bs)   | p == q, length as == length bs -> Just (zip as bs)
      (NRel p as, NRel q bs) | p == q, length as == length bs -> Just (zip as bs)
      _ -> Nothing
    rebuild lp ts = case (lp, ts) of
      (Eq _ _, [a, b])  -> Just (Eq a b)
      (NEq _ _, [a, b]) -> Just (NEq a b)
      (Rel p _, _)      -> Just (Rel p ts)
      (NRel p _, _)     -> Just (NRel p ts)
      _                 -> Nothing

-- The cited clause applied at the instance that derives the literal, as a
-- term.  Each body atom is one of the premises, up to the orientation of an
-- equation, or it is an equation whose two sides the instance makes equal,
-- which holds by reflexivity.  That is equality resolution, as when
-- c2 = X => c1 = X is cited for c1 = c2.  Premises are tried first, so
-- reflexivity only closes what no premise states.
applyClause :: Ctx -> Env -> Ref -> Literal -> [(String, Literal)] -> Maybe String
applyClause ctx env r l prems = listToMaybe
  [ if flipped then symm l t else t
  | (s0, flipped) <- case refHead r of
      Nothing -> [ (Map.empty, False) | l == falsumLit ]
      Just h  -> matchL isPattern h l Map.empty
  , (s1, slots) <- assign (refBody r) s0 []
  , Just (s, args) <- [reflexive s1 slots]
  , let t = unwords (instantiate ctx env r s : args) ]
  where
    -- a body atom takes a premise, or waits to be closed by reflexivity
    assign [] s acc = [(s, reverse acc)]
    assign (b : bs) s acc =
      [ res
      | (hp, lp) <- prems
      , (s', flipped) <- matchL isPattern b lp s
      , res <- assign bs s' (Left (if flipped then "(" ++ symm lp hp ++ ")" else hp) : acc) ]
      ++ [ res | Eq x y <- [b], res <- assign bs s (Right (x, y) : acc) ]
    reflexive s [] = Just (s, [])
    reflexive s (Left t : rest) = fmap (t :) <$> reflexive s rest
    reflexive s (Right (x, y) : rest) = do
      let (x', y') = (applySub s x, applySub s y)
      s' <- if closed y' then matchT isPattern x' y' s
            else if closed x' then matchT isPattern y' x' s
            else Nothing
      fmap ("rfl" :) <$> reflexive s' rest
    closed t = not (any isPattern (termVars t))

applySub :: Sub -> Term -> Term
applySub s t = case t of
  Var v    -> Map.findWithDefault t v s
  App f ts -> App f (map (applySub s) ts)
  _        -> t

-- A local name that no symbol and no variable of the proof has.
localName :: Ctx -> Env -> String -> String
localName ctx env x = head [ y | y <- iterate (++ "_") x
                               , y `Set.notMember` ctxUsed ctx, y `notElem` Map.elems env ]

-- A chain.  Under an equation it is a calculation from one side to the
-- other.  Under an atom it rewrites the atom into an instance of a stated
-- fact, which is read backwards: that fact, then each atom from the next.
chain :: Ctx -> Env -> String -> Literal -> Term -> [(RwStep, Term)] -> [String]
chain ctx env hole stmt s steps = case stmt of
  Eq a b
    | null steps, a == b, s == a  -> [ "rfl" ]
    | not (null steps), (s, final) == (a, b) -> calc
    | not (null steps), (s, final) == (b, a) -> "refine Eq.symm ?_" : calc
    | otherwise -> unjustified ("the chain runs from " ++ term ctx env s ++ " to " ++ term ctx env final
                                ++ ", which are not the sides of the statement")
  _ | isAtom stmt, ((rwLast, Const "true") : revSteps) <- reverse steps
    , Just atoms <- mapM termAtom (atomTerms s steps), head atoms == stmt ->
        relational (reverse revSteps) rwLast atoms
  _ -> unjustified "the chain does not prove the statement"
  where
    final = snd (last steps)
    ref nm = Map.lookup nm (ctxRefs ctx)
    calc = case sequence (zipWith step (s : map snd steps) steps) of
      Nothing -> unjustified "a step of the chain is not an instance of the equation it cites"
      Just (l1 : ls) -> ("calc " ++ term ctx env s ++ " = " ++ l1) : map ("    _ = " ++) ls
      Just []        -> [ "rfl" ]
    step prev (rw, cur) = do
      r <- ref (rwName rw)
      (eq, [shape]) <- rewrite ctx env r [rwDir rw] [(prev, cur)]
      return (term ctx env cur ++ " := " ++ congruence (term ctx env shape) (shape == Var holeVar) eq)
    congruence shape atRoot eq
      | atRoot    = eq
      | otherwise = "congrArg (fun " ++ hole ++ " : α => " ++ shape ++ ") (" ++ eq ++ ")"
    relational rwSteps rwLast atoms =
      let lastAtom = last atoms
          start = do
            r <- ref (rwName rwLast)
            h <- refHead r
            if not (null (refBody r)) then Nothing else listToMaybe
              [ instantiate ctx env r sub | (sub, False) <- matchL isPattern h lastAtom Map.empty ]
          back (prevAtom, nextAtom, rw) = do
            r <- ref (rwName rw)
            (Rel p as, Rel q bs) <- Just (prevAtom, nextAtom)
            if p /= q || length as /= length bs then Nothing else do
              (eq, shapes) <- rewrite ctx env r [rwDir rw] (zip as bs)
              return ("Eq.mpr (congrArg (fun " ++ hole ++ " : α => " ++ literal ctx env (Rel p shapes) ++ ") (" ++ eq ++ "))")
      in case (start, mapM back (zip3 atoms (drop 1 atoms) (map fst rwSteps))) of
           (Just t0, Just backs) ->
             let names = [ localName ctx env ("h" ++ show i) | i <- [(1 :: Int) ..] ]
                 facts = reverse atoms
                 first = "have " ++ head names ++ " : " ++ literal ctx env (head facts) ++ " := " ++ t0
                 rest  = [ "have " ++ n ++ " : " ++ literal ctx env a ++ " := " ++ b ++ " " ++ p
                         | (n, p, a, b) <- zip4' (drop 1 names) names (drop 1 facts) (reverse backs) ]
             in first : rest ++ [ "exact " ++ names !! (length facts - 1) ]
           _ -> unjustified "a step of the chain is not an instance of the statement it cites"
    zip4' (a : as) (b : bs) (c : cs) (d : ds) = (a, b, c, d) : zip4' as bs cs ds
    zip4' _ _ _ _ = []
