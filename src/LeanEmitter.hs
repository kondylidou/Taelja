-- The structured proof as a Lean 4 file that checks it.  Every symbol is
-- declared over one uninterpreted nonempty sort, every axiom is a Lean axiom,
-- and every lemma and goal is a theorem whose proof follows the block line by
-- line.  A step is a term built from the statement it cites and the premises
-- written before it and from nothing else: a have or hence line applies the
-- cited clause to explicit arguments, and a rewrite is congruence at the
-- rewritten subterm with the cited equation instantiated explicitly.  No
-- search tactic is used, so Lean accepts the file only if each step is the
-- inference the proof says it is.  A step that cannot be stated this way is
-- left as an undefined name, which Lean rejects.
module LeanEmitter (emitLean) where

import Control.Monad (foldM, zipWithM)
import Data.Char (isAlpha, isAlphaNum, isDigit, ord)
import Data.List (intercalate, nub, (\\))
import qualified Data.Map.Strict as Map
import Data.Maybe (listToMaybe, maybeToList)
import qualified Data.Set as Set

import Emitter (finalProof)
import Helpers (blockShownVars, falsumLit, litVars, mapLiteralTerms, termVars)
import Types

-- Symbols.  A function and a predicate may share a name, and one name may be
-- used at several arities, so a symbol is its kind, name and arity.
data Kind = Fun | Pred deriving (Eq, Ord, Show)
type Sym = (Kind, String, Int)

data Ctx = Ctx
  { ctxNames :: Map.Map Sym String     -- the Lean name of each symbol
  , ctxUsed  :: Set.Set String         -- names a local name must avoid
  , ctxRefs  :: Map.Map String Ref     -- "axiom 3", "lemma 7"
  }

-- A citable statement, with its variables renamed apart from every block by
-- a leading '?', in the order its Lean statement binds them.
data Ref = Ref
  { refName    :: String
  , refBinders :: [String]
  , refBody    :: [Literal]
  , refHead    :: Maybe Literal
  }

type Env = Map.Map String String       -- variable to its Lean name
type Sub = Map.Map String Term

-- The declarations are wrapped in a namespace, the one given or TaeljaProof,
-- so that a symbol named like a Lean constant, as id or max, declares a name
-- of its own, and so that several files can be imported together.
emitLean :: String -> StructuredProof -> String
emitLean namespace0 sp0 = unlines $
  [ "-- Generated by taelja --lean"
  , "-- Lean 4 verification of the Taelja proof"
  , ""
  , "namespace " ++ namespace
  , "" ]
  ++ [ "-- Uninterpreted sort, nonempty as every first-order domain is"
     , "axiom α : Type"
     , "axiom taelja_nonempty : Nonempty α"
     , "noncomputable def taelja_elem : α := Classical.choice taelja_nonempty"
     , "" ]
  ++ symbolDecls
  ++ concat [ [ "-- " ++ capital n, "axiom " ++ refName r ++ " : " ++ refType ctx r ]
            | (n, r) <- axiomRefs ]
  ++ [ "" | not (null axiomRefs) ]
  ++ concat [ [ "-- " ++ capital n
              , "theorem " ++ leanRefName n ++ " : " ++ statement ctx lit ++ " := by" ]
              ++ map ("  " ++) (proofLines ctx lit blk) ++ [""]
            | (n, lit, blk) <- lemmas sp ]
  ++ concat [ [ "-- Goal " ++ show i
              , "theorem taelja_goal" ++ show i ++ " : " ++ statement ctx lit ++ " := by" ]
              ++ map ("  " ++) (proofLines ctx lit blk) ++ [""]
            | (i, (lit, blk)) <- zip [(1 :: Int) ..] (goals sp) ]
  ++ [ "end " ++ namespace ]
  where
    namespace = if null namespace0 then "TaeljaProof" else namespace0
    sp = finalProof sp0
    syms = Set.toList . Set.fromList $
      concat [ concatMap litSyms (axiomLits ax) | ax <- axioms sp ]
      ++ concat [ litSyms lit ++ blockSyms lit blk | (_, lit, blk) <- lemmas sp ]
      ++ concat [ litSyms lit ++ blockSyms lit blk | (lit, blk) <- goals sp ]
    names = symbolNames syms
    axiomRefs = [ (axiomName ax, axiomRef ax) | ax <- axioms sp ]
    lemmaRefs = [ (n, mkRef (leanRefName n) [] (Just lit)) | (n, lit, _) <- lemmas sp ]
    ctx = Ctx { ctxNames = names
              , ctxUsed  = Set.fromList (Map.elems names)
              , ctxRefs  = Map.fromList (axiomRefs ++ lemmaRefs) }
    symbolDecls =
      let decl s@(k, _, n) = "axiom " ++ names Map.! s ++ " : "
            ++ intercalate " → " (replicate n "α" ++ [if k == Fun then "α" else "Prop"])
          consts = [ s | s@(Fun, _, 0) <- syms ]
          funs   = [ s | s@(Fun, _, n) <- syms, n > 0 ]
          preds  = [ s | s@(Pred, _, _) <- syms ]
      in concat [ map decl g ++ [""] | g <- [consts, funs, preds], not (null g) ]

axiomName :: Axiom -> String
axiomName (AUnit n _)    = n
axiomName (ANucleus n _) = n

axiomLits :: Axiom -> [Literal]
axiomLits (AUnit _ l)                 = [l]
axiomLits (ANucleus _ (Clause bs mh)) = bs ++ maybeToList mh

axiomRef :: Axiom -> Ref
axiomRef (AUnit n l)                 = mkRef (leanRefName n) [] (Just l)
axiomRef (ANucleus n (Clause bs mh)) = mkRef (leanRefName n) bs mh

mkRef :: String -> [Literal] -> Maybe Literal -> Ref
mkRef nm bs mh = Ref nm (map ('?' :) vs) (map apart bs) (fmap apart mh)
  where
    vs    = nub (concatMap litVars (bs ++ maybeToList mh))
    apart = mapLiteralTerms rename
    rename (Var v)    = Var ('?' : v)
    rename (App f ts) = App f (map rename ts)
    rename t          = t

-- "axiom 3" is ax3 and "lemma 7" is taelja_lemma7.
leanRefName :: String -> String
leanRefName n = case words n of
  ["axiom", k] -> "ax" ++ k
  ["lemma", k] -> "taelja_lemma" ++ k
  _            -> "taelja_" ++ filter isAlphaNum n

capital :: String -> String
capital (c : cs) | c >= 'a', c <= 'z' = toEnum (fromEnum c - 32) : cs
capital s = s

-- Symbols ----------------------------------------------------------------

termSyms :: Term -> [Sym]
termSyms (Var _)    = []
termSyms (Const c)  = [(Fun, c, 0)]
termSyms (App f ts) = (Fun, f, length ts) : concatMap termSyms ts

-- $false and $true are Lean's False and True, not symbols of the problem.
reservedAtom :: String -> Bool
reservedAtom p = p == "$false" || p == "$true"

litSyms :: Literal -> [Sym]
litSyms l = case l of
  Eq a b    -> termSyms a ++ termSyms b
  NEq a b   -> termSyms a ++ termSyms b
  Rel p ts  -> atom p ts
  NRel p ts -> atom p ts
  where atom p ts | reservedAtom p = []
                  | otherwise      = (Pred, p, length ts) : concatMap termSyms ts

-- A chain under a relational statement rewrites the atom as a term and ends
-- in true, so its terms are atoms and that true is no constant.
blockSyms :: Literal -> ProofBlock -> [Sym]
blockSyms _ (HaveHence ls) = concatMap (litSyms . lineLit) ls
blockSyms stmt (EqChain s steps)
  | isAtom stmt = concat [ litSyms a | t <- atomTerms s steps, Just a <- [termAtom t] ]
  | otherwise   = concatMap termSyms (s : map snd steps)

isAtom :: Literal -> Bool
isAtom (Rel p _) = not (reservedAtom p)
isAtom _         = False

-- The atoms of a relational chain, without the closing true.
atomTerms :: Term -> [(RwStep, Term)] -> [Term]
atomTerms s steps = s : [ t | (_, t) <- dropLastTrue steps ]
  where dropLastTrue xs = case reverse xs of
          (_, Const "true") : rest -> reverse rest
          _                        -> xs

termAtom :: Term -> Maybe Literal
termAtom (App p ts) = Just (Rel p ts)
termAtom (Const p)  = Just (Rel p [])
termAtom (Var _)    = Nothing

lineLit :: ProofLine -> Literal
lineLit (Have l _)  = l
lineLit (And l _)   = l
lineLit (Hence l _) = l

-- Each symbol gets a Lean identifier of its own.  A name Lean reserves, one
-- this file generates, or one another symbol already took gets underscores
-- appended, and a character no identifier may hold is spelled by its code.
symbolNames :: [Sym] -> Map.Map Sym String
symbolNames = foldl add Map.empty
  where
    add m s@(_, n, _) = Map.insert s (fresh (Set.fromList (Map.elems m)) (identifier n)) m
    fresh taken x | x `Set.member` taken || reservedName x = fresh taken (x ++ "_")
                  | otherwise                              = x

identifier :: String -> String
identifier n
  | all plain n, (c : _) <- n, isAlpha c || c == '_' = n
  | all plain n, (c : _) <- n, isDigit c             = "n_" ++ n
  | otherwise = "op_" ++ intercalate "_" (words' n)
  where
    plain c = c < '\128' && (isAlphaNum c || c == '_')
    -- runs of plain characters stay, every other character is spelled out
    words' [] = []
    words' cs@(c : rest)
      | plain c   = let (w, more) = span plain cs in w : words' more
      | otherwise = spell c : words' rest
    spell c = case lookup c symbolWords of
      Just w  -> w
      Nothing -> "c" ++ show (ord c)
    symbolWords =
      [ ('+', "plus"), ('-', "minus"), ('*', "times"), ('/', "div"), ('^', "pow"), ('<', "lt")
      , ('>', "gt"), ('=', "eq"), (' ', "sp"), ('%', "mod"), ('&', "and"), ('|', "or")
      , ('~', "tilde"), ('.', "dot"), ('$', "dollar"), ('\'', "prime"), ('!', "bang"), ('?', "q")
      , ('@', "at"), ('#', "hash") ]

reservedName :: String -> Bool
reservedName x = x `Set.member` leanKeywords
  || take 7 x == "taelja_"
  || (take 2 x == "ax" && all isDigit (drop 2 x))

